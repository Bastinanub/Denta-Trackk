-- ---------------------------------------------------------------------------
-- UHID counter + generator function
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS uhid_counters (
  year        int PRIMARY KEY,
  next_seq    bigint NOT NULL DEFAULT 1
);
ALTER TABLE uhid_counters ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION generate_uhid()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_year    int := EXTRACT(YEAR FROM now())::int;
  v_seq     bigint;
BEGIN
  INSERT INTO uhid_counters (year, next_seq)
  VALUES (v_year, 2)
  ON CONFLICT (year)
  DO UPDATE SET next_seq = uhid_counters.next_seq + 1
  RETURNING next_seq INTO v_seq;

  v_seq := v_seq - 1;
  RETURN 'DNT-' || v_year || '-' || lpad(v_seq::text, 6, '0');
END;
$$;

REVOKE ALL ON FUNCTION generate_uhid() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION generate_uhid() TO authenticated;

CREATE OR REPLACE FUNCTION assign_uhid()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.uhid IS NULL THEN
    NEW.uhid := generate_uhid();
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_patients_assign_uhid ON patients;
CREATE TRIGGER trg_patients_assign_uhid
BEFORE INSERT ON patients
FOR EACH ROW EXECUTE FUNCTION assign_uhid();

