/*
# Dental Clinic V1 — Core Schema

## Purpose
Foundation for a simplified dental patient management / clinical record system.
V1 workflow: PATIENT -> VISIT -> CLINICAL RECORD -> DENTAL CHART (FDI) -> MEDIA -> HISTORY.

## 1. New Tables
- `staff`            : mirror of auth.users with clinic role (dentist/admin) and full name.
- `patients`         : demographics + medical history + allergies. Server-generated UHID.
- `visits`           : a single consultation/visit. record_type is GENERAL or DENTAL_STATUS.
- `diagnoses`        : free-text diagnoses, optionally tied to a single tooth.
- `tooth_conditions` : per-tooth condition marking for a visit (FDI tooth number + surface).
- `clinical_notes`   : addenda / extra notes attached to a visit.
- `condition_definitions` : configurable labels + colors for dental-status markings.
- `media`            : metadata for clinical photos/videos; files live in private Storage.
- `audit_logs`       : append-only audit trail of actor + action + entity + details.

## 2. UHID Generation
- `generate_uhid()` SECURITY DEFINER function: atomically increments a per-year counter
  stored in `uhid_counters` and returns `DNT-YYYY-NNNNNN` (zero-padded 6 digits).
  Used by a trigger on `patients` so UHID is ALWAYS assigned server-side, never client-supplied.

## 3. Foreign Keys & Indexes
- visits.patient_id -> patients(id) ON DELETE CASCADE
- diagnoses.visit_id -> visits(id) ON DELETE CASCADE
- tooth_conditions.visit_id -> visits(id) ON DELETE CASCADE
- clinical_notes.visit_id -> visits(id) ON DELETE CASCADE
- media.patient_id -> patients(id), media.visit_id -> visits(id) ON DELETE SET NULL
- staff.id -> auth.users(id) ON DELETE CASCADE
- Indexes on uhid, name, mobile, visit dates, tooth numbers, media patient/visit.

## 4. Security (RLS)
- All tables: RLS ENABLED, `TO authenticated`, scoped via staff membership check:
  EXISTS (SELECT 1 FROM staff WHERE staff.id = auth.uid()).
- patients/visits/clinical data: any authenticated staff member can read & write
  (small clinic, shared records). This is intentional shared data, not a per-user ownership model.
- audit_logs: authenticated staff can INSERT; only staff can SELECT.
- condition_definitions: authenticated staff can SELECT; INSERT/UPDATE/DELETE allowed
  (definitions are configurable). This is documented as intentionally shared writeable config.
- uhid_counters: NOT directly accessible; only via the SECURITY DEFINER generate_uhid().
- generate_uhid() executable by authenticated.

## 5. Important Notes
1. UHID is unique and generated by a BEFORE INSERT trigger -> clients never pass UHID.
2. UUIDs are the primary keys everywhere; UHID is a separate human-readable identifier.
3. Media files are stored in Supabase Storage private bucket `clinical-media`;
   this table only stores metadata + storage path. Signed URLs are used for viewing.
4. record_type is constrained to exactly two values: GENERAL and DENTAL_STATUS.
   No other "dental status" levels exist in V1; condition_definitions make them configurable.
*/

